'use strict';
const vscode = require('vscode');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const manifest = require('../package.json');

exports.run = async () => {
  const extension = vscode.extensions.getExtension(`${manifest.publisher}.${manifest.name}`);
  assert.ok(extension, 'Extension registered');
  await extension.activate();
  const checks = [];
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'qf-fixture-'));
  const original = '```{r}\nx <- 1\ny <- 2\nz <- 3\n```\n';
  const file = path.join(directory, 'example.qmd');
  fs.writeFileSync(file, original);
  const doc = await vscode.workspace.openTextDocument(file);
  const editor = await vscode.window.showTextDocument(doc);
  checks.push('activation');
  const command = () => vscode.commands.executeCommand('quartoFeedback.add');
  editor.selection = new vscode.Selection(1, 0, 3, 0);
  await command();
  assert.equal(doc.getText(), '```{r}\nx <- 1 # <1>\ny <- 2 # <1>\nz <- 3\n```\n\n1. \n');
  assert.deepEqual([editor.selection.active.line, editor.selection.active.character], [6, 3]);
  checks.push('shared annotation', 'exclusive final line', 'cursor below chunk');
  await vscode.commands.executeCommand('undo');
  assert.equal(doc.getText(), original);
  checks.push('atomic undo');
  editor.selection = new vscode.Selection(2, 6, 1, 0);
  await command();
  assert.equal((doc.getText().match(/# <1>/g) || []).length, 2);
  checks.push('reverse selection');
  await vscode.commands.executeCommand('type', { text: 'Почему такая модель?' });
  editor.selection = new vscode.Selection(1, 0, 1, 0);
  const before = doc.getText();
  await command();
  assert.equal(doc.getText(), before, 'Navigation must not change feedback');
  assert.equal(doc.getText(editor.selection), 'Почему такая модель?');
  await vscode.commands.executeCommand('type', { text: 'Explain this model.' });
  assert.ok(doc.getText().endsWith('1. Explain this model.\n'));
  checks.push('select existing feedback', 'type replacement inline');
  editor.selection = new vscode.Selection(3, 0, 3, 0);
  await command();
  assert.ok(doc.getText().includes('z <- 3 # <2>'));
  assert.deepEqual([editor.selection.active.line, editor.selection.active.character], [7, 3]);
  checks.push('next annotation number');
  await doc.save();
  await vscode.commands.executeCommand('workbench.action.closeActiveEditor');

  const windowsFile = path.join(directory, 'windows.QMD');
  fs.writeFileSync(windowsFile, original.replaceAll('\n', '\r\n'));
  const windowsDoc = await vscode.workspace.openTextDocument(windowsFile);
  const windowsEditor = await vscode.window.showTextDocument(windowsDoc);
  windowsEditor.selection = new vscode.Selection(1, 0, 2, 6);
  await command();
  assert.equal(windowsDoc.eol, vscode.EndOfLine.CRLF);
  assert.equal(windowsDoc.getText().replaceAll('\r\n', '').includes('\n'), false);
  assert.ok(windowsDoc.getText().includes('x <- 1 # <1>\r\ny <- 2 # <1>'));
  checks.push('CRLF preservation', 'uppercase extension');
  await windowsDoc.save();
  await vscode.commands.executeCommand('workbench.action.closeActiveEditor');
  fs.rmSync(directory, { recursive: true, force: true });
  const output = process.env.QF_TEST_RESULTS;
  assert.ok(output, 'Set QF_TEST_RESULTS to an output JSON path');
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, JSON.stringify({ passed: true, app: vscode.env.appName, vscodeVersion: vscode.version, extension: `${manifest.publisher}.${manifest.name}@${manifest.version}`, checkedAt: new Date().toISOString(), checks }, null, 2) + '\n');
};
